-- countdown schema (system MySQL, database `countdown`).
--
-- The records live here rather than in the phone's own storage: the device holds a
-- view, not the only copy, so a wipe or a reinstall costs nothing. Sixty days into a
-- hundred-day goal is exactly the kind of thing that must survive a lost phone.
--
-- A delete is a real DELETE. Undo is the client re-creating what it still holds in
-- memory for the length of the snackbar — not a row lingering with a flag on it.
-- Deleting a countdown cascades to its ticks.
--
-- Re-runnable: `sudo mysql countdown < db/schema.sql`.

SET NAMES utf8mb4;

-- One goal you are counting down: 100 days of work, 30 runs.
-- `start_count` is where it began and is never decremented — what is left is always
-- derived (start_count minus the ticks), so the number you started from stays known.
CREATE TABLE IF NOT EXISTS countdowns (
  id           VARCHAR(40)  NOT NULL PRIMARY KEY,     -- generated by the client
  name         VARCHAR(64)  NOT NULL,
  start_count  INT          NOT NULL,
  unit         VARCHAR(24)  NOT NULL DEFAULT 'days',
  accent       TINYINT      NOT NULL DEFAULT 0,
  once_per_day TINYINT      NOT NULL DEFAULT 1,       -- a second tick on one day asks first
  created_at   TIMESTAMP    NOT NULL,
  updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- One step counted off. One row is always exactly one — a count of rows is the
-- count of what was done, with nothing to sum and nothing to get wrong.
CREATE TABLE IF NOT EXISTS ticks (
  id           VARCHAR(40)  NOT NULL PRIMARY KEY,
  countdown_id VARCHAR(40)  NOT NULL,
  note         VARCHAR(255) NOT NULL DEFAULT '',
  at           TIMESTAMP    NOT NULL,
  KEY idx_countdown (countdown_id, at),
  CONSTRAINT fk_tick_countdown FOREIGN KEY (countdown_id) REFERENCES countdowns(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
